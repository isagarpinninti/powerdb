#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md: every library that ends up in a PowerDB build, with its version and licence, taken from the
lock files. Run from the repository root after changing dependencies:  python3 tools/notices.py"""
import json, re, subprocess, sys
from collections import Counter

def rust(manifest):
    cmd = ["cargo", "tree", "--edges", "normal", "--prefix", "none", "--target", "all", "--format", "{p}|{l}|{r}", "--manifest-path", manifest]
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    seen = {}
    for line in out.splitlines():
        m = re.match(r"^(\S+) v(\S+)(?: \([^)]*\))?\|(.*?)\|(.*)$", line.strip())
        if m and "(*)" not in m.group(1):
            name, ver, lic, repo = m.groups()
            seen[(name, ver)] = (lic.strip() or "unspecified", repo.strip())
    return seen

def npm(lock):
    j = json.load(open(lock))
    out = {}
    for path, p in j["packages"].items():
        if not path or p.get("dev") or "node_modules/" not in path:
            continue
        name = path.split("node_modules/")[-1]
        out[(name, p.get("version", "?"))] = (p.get("license", "unspecified"), "")
    return out

sections = [
    ("Server and command-line tool (Rust)", rust("engine/Cargo.toml")),
    ("Desktop app shell (Rust)", rust("desktop/src-tauri/Cargo.toml")),
    ("Dashboard (JavaScript)", npm("dashboard/package-lock.json")),
    ("Desktop app interface (JavaScript)", npm("desktop/package-lock.json")),
]
own = {"powerdb", "powerdb-desktop", "powerdb-sdk", "powerdb-dashboard"}
copyleft = re.compile(r"\b(A?GPL|LGPL|SSPL|EUPL|CC-BY-NC)\b", re.I)
lines = ["# Third-party notices", "",
         "PowerDB itself is MIT licensed (see LICENSE). It is built from the libraries below, each under its own licence, which is the licence",
         "named here (an `OR` means the library is offered under either; PowerDB uses the permissive one where there is a choice).",
         "Generated by `tools/notices.py` from the lock files; regenerate it when dependencies change.", ""]
flagged = []
for title, pk in sections:
    pk = {k: v for k, v in pk.items() if k[0] not in own}
    c = Counter(v[0] for v in pk.values())
    lines += [f"## {title}", "", f"{len(pk)} packages. Licences: " + ", ".join(f"{l} ({n})" for l, n in c.most_common(8)) + ("…" if len(c) > 8 else ""), "",
              "| Package | Version | Licence |", "|---|---|---|"]
    for (name, ver), (lic, repo) in sorted(pk.items()):
        lines.append(f"| {name} | {ver} | {lic.replace('|', '/')} |")
        if copyleft.search(lic):
            flagged.append((title, name, ver, lic))
    lines.append("")
if flagged:
    lines += ["## Dual-licensed libraries with a copyleft option", "",
              "These offer a copyleft licence as one choice among several. PowerDB uses them under the permissive choice (MIT or Apache-2.0),",
              "so no copyleft obligation applies. A review of the licence lists above found no library that is available only under copyleft terms.", "",
              "| Package | Version | Offered under |", "|---|---|---|"]
    for name, ver, lic in sorted({(n, v, l) for _, n, v, l in flagged}):
        lines.append(f"| {name} | {ver} | {lic} |")
    lines.append("")
lines += ["## Weak copyleft (MPL-2.0)", "",
          "Some libraries are under the Mozilla Public License 2.0, a file-level licence: it asks that changes to *those files* be shared under the",
          "same licence. PowerDB uses them unmodified, from their published releases, so there is nothing to share beyond pointing at their source.", ""]
open("THIRD_PARTY_NOTICES.md", "w").write("\n".join(lines))
print(f"wrote THIRD_PARTY_NOTICES.md: {sum(len(s[1]) for s in sections)} entries")
for f in flagged:
    print("REVIEW (copyleft-looking licence):", f)
